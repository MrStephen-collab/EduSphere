-- =============================================================================
-- EduSphere — Online admission
--
-- An applicant (or their guardian) fills in the public application form on a
-- school's website. There is no account on the other side: the form is the one
-- write path in the product that a signed-out visitor can reach, so it is
-- handled by a route handler that writes through the service role and never by
-- an RLS policy on `anon`. The school then works the application through the
-- workflow from its admin console:
--
--   submitted  -> under_review -> entrance -> offered -> enrolled
--                              \-> rejected
--                              \-> withdrawn
--
-- `admission_events` is the thread beside an application: every hospital pass,
-- status move, entrance score and free-text note, in the order it happened.
-- Keeping events in their own table (rather than a single `notes` blob) means
-- the timeline can show who did what and when without the school having to
-- reconstruct it from the last `updated_at`.
--
-- Access model: only school admins (and a super admin) may read or write
-- applications and events. There is deliberately no `anon` policy -- the public
-- form is served by trusted server code, so a leaked anon key cannot enumerate
-- or forge applications.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
do $$ begin
  create type public.admission_status as enum (
    'submitted', 'under_review', 'entrance', 'offered', 'enrolled', 'rejected', 'withdrawn'
  );
exception when duplicate_object then null; end $$;

-- The notification type mirrors the one moment an admin is told about: a fresh
-- public application arriving.
alter type public.notification_type add value if not exists 'admission_application_received';

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table if not exists public.admission_applications (
  id uuid primary key default gen_random_uuid(),
  school_id uuid not null references public.schools (id) on delete cascade,
  -- Human-quotable reference, unique within the school. Generated by the
  -- service (src/lib/admission.ts) so it is testable without a database.
  application_number text not null,
  applicant_first_name text not null,
  applicant_last_name text not null,
  date_of_birth date,
  gender text check (gender is null or gender in ('male', 'female')),
  -- The class applied for. Kept alongside a denormalised label so the
  -- application still reads correctly after the class is renamed or removed.
  class_id uuid references public.classes (id) on delete set null,
  class_name text not null default '',
  guardian_name text not null,
  guardian_email text not null,
  guardian_phone text,
  address text,
  previous_school text,
  -- The applicant's own message / anything else they want the school to know.
  notes text,
  status public.admission_status not null default 'submitted',
  -- Entrance assessment: scored by a human against the paper, so it is a plain
  -- number the school types in rather than something the platform computes.
  entrance_score numeric(5,2)
    check (entrance_score is null or (entrance_score >= 0 and entrance_score <= 100)),
  entrance_date date,
  -- The school's reason for the decision, surfaced on the letter.
  decision_note text,
  reviewed_by uuid references public.profiles (id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (school_id, application_number)
);

create table if not exists public.admission_events (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.admission_applications (id) on delete cascade,
  -- Denormalised so the timeline never has to join back for a school scope.
  school_id uuid not null references public.schools (id) on delete cascade,
  author_id uuid references public.profiles (id) on delete set null,
  author_name text not null default 'System',
  -- note | status | score | system. Free text rather than an enum: the timeline
  -- is a log, and a new kind of event should never require a migration.
  kind text not null default 'note',
  body text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------
-- The inbox: a school's applications, newest first, filterable by status.
create index if not exists admission_applications_school_status_idx
  on public.admission_applications (school_id, status, created_at desc);
create index if not exists admission_applications_class_idx
  on public.admission_applications (class_id)
  where class_id is not null;
-- A guardian asking "what happened to my application?" is looked up by email.
create index if not exists admission_applications_email_idx
  on public.admission_applications (school_id, lower(guardian_email));
-- Reading a timeline: its events in order.
create index if not exists admission_events_thread_idx
  on public.admission_events (application_id, created_at);

-- ---------------------------------------------------------------------------
-- Access helper — shared by both tables so a timeline is never half-visible
-- ---------------------------------------------------------------------------
create or replace function public.can_access_admission(p_application_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admission_applications a
    where a.id = p_application_id
      and (public.is_super_admin() or public.is_school_admin(a.school_id))
  );
$$;

-- ---------------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------------
alter table public.admission_applications enable row level security;

drop policy if exists p_admission_applications_select_admin on public.admission_applications;
create policy "p_admission_applications_select_admin"
  on public.admission_applications for select
  using (public.is_super_admin() or public.is_school_admin(school_id));

-- No INSERT policy: the public form is written by trusted server code through
-- the service role. Creating one here would let anyone holding the anon key
-- file applications into any school.

drop policy if exists p_admission_applications_update_admin on public.admission_applications;
create policy "p_admission_applications_update_admin"
  on public.admission_applications for update
  using (public.is_super_admin() or public.is_school_admin(school_id))
  with check (public.is_super_admin() or public.is_school_admin(school_id));

drop policy if exists p_admission_applications_delete_admin on public.admission_applications;
create policy "p_admission_applications_delete_admin"
  on public.admission_applications for delete
  using (public.is_super_admin() or public.is_school_admin(school_id));

alter table public.admission_events enable row level security;

drop policy if exists p_admission_events_select_admin on public.admission_events;
create policy "p_admission_events_select_admin"
  on public.admission_events for select
  using (public.can_access_admission(application_id));

-- Events are written by the service role only, and never edited or deleted --
-- a timeline that can be rewritten is not a record.

-- ---------------------------------------------------------------------------
-- updated_at on the application (status, score and decision change after it)
-- ---------------------------------------------------------------------------
drop trigger if exists admission_applications_set_updated_at on public.admission_applications;
create trigger admission_applications_set_updated_at
  before update on public.admission_applications
  for each row
  execute function public.set_updated_at();
